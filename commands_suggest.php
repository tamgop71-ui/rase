/**
 * Конвертация забытой раскладки клавиатуры (EN <-> RU)
 */
function swapKeyboardLayout(string $str): string {
    static $en = ['q','w','e','r','t','y','u','i','o','p','a','s','d','f','g','h','j','k','l','z','x','c','v','b','n','m'];
    static $ru = ['й','ц','у','к','е','н','г','ш','щ','з','ф','ы','в','а','п','р','о','л','д','я','ч','с','м','и','т','ь'];

    // Если строка в основном латинская — переводим в русскую, иначе наоборот
    if (preg_match('/^[a-z0-9_]+$/u', $str)) {
        return str_replace($en, $ru, $str);
    }
    return str_replace($ru, $en, $str);
}

/**
 * Точное расстояние Левенштейна для UTF-8 строк (кириллица + латиница)
 */
function mbLevenshtein(string $s1, string $s2): int {
    if ($s1 === $s2) return 0;
    $a = preg_split('//u', $s1, -1, PREG_SPLIT_NO_EMPTY);
    $b = preg_split('//u', $s2, -1, PREG_SPLIT_NO_EMPTY);
    $lenA = count($a);
    $lenB = count($b);
    if ($lenA === 0) return $lenB;
    if ($lenB === 0) return $lenA;

    $prev = range(0, $lenB);
    for ($i = 1; $i <= $lenA; $i++) {
        $curr = [$i];
        for ($j = 1; $j <= $lenB; $j++) {
            $cost = ($a[$i - 1] === $b[$j - 1]) ? 0 : 1;
            $curr[$j] = min(
                $prev[$j] + 1,
                $curr[$j - 1] + 1,
                $prev[$j - 1] + $cost
            );
        }
        $prev = $curr;
    }
    return $prev[$lenB];
}

/**
 * Поиск самой похожей команды и отправка подсказки с описанием и кнопкой запуска
 */
function suggestClosestCommand(PDO $pdo, string $prefix, string $rawCmd, string $args, int $peerId, int $myPriority, bool $isSuper): void {
    // Игнорируем слишком короткий шум и чисто числа (например, +1, -5, .а)
    $rawLen = mb_strlen($rawCmd);
    if ($rawLen < 2 || ctype_digit($rawCmd)) {
        return;
    }
    // Для префиксов +, -, . в обычном чате требуем хотя бы 3 символа, чтобы не спамить на "+я", "-да", "..а"
    if (in_array($prefix, ['+', '-', '.'], true) && $rawLen < 3) {
        return;
    }

    $aliasMap = getCommandAliasMap();
    $descs = getCommandDescriptions();

    // 1. Проверяем точную опечатку раскладки клавиатуры (например !ghjabkm -> !профиль)
    $swapped = swapKeyboardLayout($rawCmd);
    if ($swapped !== $rawCmd && isset($aliasMap[$swapped])) {
        $canon = $aliasMap[$swapped];
        if (isset($descs[$canon])) {
            $defPrio = getDefaultCmdPriority($canon);
            if ($isSuper || ($defPrio !== 999 && $myPriority >= $defPrio)) {
                sendCommandSuggestion($peerId, $prefix, $rawCmd, $swapped, $descs[$canon]['desc'], $args);
                return;
            }
        }
    }

    // 2. Нечёткий поиск по всем доступным пользователю алиасам
    $bestCanon = null;
    $bestAlias = null;
    $bestScore = 0.0;
    $bestDist  = 99;

    foreach ($aliasMap as $alias => $canon) {
        if (!isset($descs[$canon])) continue; // пропускаем скрытые (koch, superreq)
        $defPrio = getDefaultCmdPriority($canon);
        if (!$isSuper && ($defPrio === 999 || $myPriority < $defPrio)) {
            continue;
        }

        $aLen = mb_strlen($alias);
        if (abs($aLen - $rawLen) > 3) continue; // быстрое отсечение

        $dist = mbLevenshtein($rawCmd, $alias);
        $maxLen = max($rawLen, $aLen);
        $sim = 1.0 - ($dist / $maxLen);

        // Небольшой бонус, если совпадает начало слова
        if ($rawLen >= 3 && str_starts_with($alias, mb_substr($rawCmd, 0, 3))) {
            $sim += 0.08;
        }

        if ($sim > $bestScore || ($sim === $bestScore && $dist < $bestDist)) {
            $bestScore = $sim;
            $bestDist  = $dist;
            $bestCanon = $canon;
            $bestAlias = $alias;
        }
    }

    // Порог срабатывания: защищает от ложных срабатываний на случайные слова вроде "!привет" или "-пока"
    $maxLenBest = $bestAlias !== null ? max($rawLen, mb_strlen($bestAlias)) : 0;
    $isClose = ($bestCanon !== null) && (
        ($bestDist === 1 && $maxLenBest >= 3) ||
        ($bestDist === 2 && $maxLenBest >= 4 && $bestScore >= 0.58) ||
        ($bestDist === 3 && $maxLenBest >= 6 && $bestScore >= 0.62)
    );

    if (!$isClose) {
        return;
    }

    // Показываем либо совпавший алиас (если пользователь писал на том же языке), либо основной красивый вариант
    $displayCmd = $bestAlias;
    $desc = $descs[$bestCanon]['desc'];
    sendCommandSuggestion($peerId, $prefix, $rawCmd, $displayCmd, $desc, $args);
}

function sendCommandSuggestion(int $peerId, string $prefix, string $rawCmd, string $suggestedCmd, string $desc, string $args): void {
    $fullSuggested = $prefix . $suggestedCmd;
    $text = "❓ Команда «{$prefix}{$rawCmd}» не найдена.\n"
          . "💡 Возможно, вы имели в виду: {$fullSuggested}\n"
          . "📖 Что делает: {$desc}.";

    $kb = null;
    $payloadCmd = $fullSuggested . ($args !== '' ? ' ' . $args : '');
    if (mb_strlen($payloadCmd) <= 180) {
        $kb = makeInlineKeyboard([[
            ['label' => "▶ Выполнить {$fullSuggested}", 'payload' => ['cmd' => $payloadCmd], 'color' => 'primary']
        ]]);
    }

    sendMessage($peerId, $text, $kb);
}
